/**
  * @brief  重写 fputc，实现 printf 串口重定向（串口调试输出）
  * @note   调试口固定为 USART1：PA9=TX，PA10=RX，波特率 115200
  *         （usart.c 中 MX_USART1_UART_Init() 初始化后即可使用 printf）
  * @param  ch 待发送的字符
  * @param  f  标准库文件指针（本实现不使用）
  * @retval 返回发送成功的字符值；HAL 发送失败时返回 0（1/非0=成功，0=失败）
  */
int fputc(int ch, FILE *f)
{
  uint8_t c = (uint8_t)ch;

  /* 阻塞式发送单字节；仅允许在任务上下文调用，禁止在中断中调用 printf */
  if (HAL_UART_Transmit(&huart1, &c, 1, 0xFFFF) != HAL_OK)
  {
    return 0;
  }
  return (int)c;
}
