/**
  ******************************************************************************
  * @file    App_Fan.h
  * @brief   风扇控制应用层接口
  * @note    风扇使能脚为 PA1（原理图网络名 MOTOR_ON，高电平有效）：
  *          引脚电气属性（推挽输出、上电默认低电平=风扇关）由
  *          Core/Src/gpio.c 统一配置，本模块只负责按需拉高/拉低，
  *          不重复初始化 GPIO，也不直接操作 HAL 引脚常量。
  *          接口均为非阻塞的简单 GPIO 操作，可在任务上下文调用；
  *          内部维护运行状态标志，支持查询与切换，便于上层调用。
  *          自动跟随（推荐，业务默认行为）：Fan_Init() 创建的风扇控制
  *          任务每 200ms 检测系统状态——RUN → 风扇启动；IDLE / FAULT →
  *          风扇停止。因此业务代码通常无需手动调用 Fan_Start/Fan_Stop，
  *          手动调用会在下一次状态轮询时被状态联动覆盖。
  ******************************************************************************
  */
#ifndef __APP_FAN_H__
#define __APP_FAN_H__

#include <stdint.h>

/**
  * @brief  风扇模块初始化：置风扇停止并创建系统状态联动任务
  * @note   须在 vTaskStartScheduler() 之前调用（创建任务合法）：
  *         gpio.c 已把 PA1 配成推挽输出且上电默认低电平，本函数再显式
  *         拉低一次保证软硬件状态一致；随后创建 "FanCtrl" 任务，实现
  *         "系统运行 → 风扇启动，系统空闲/故障 → 风扇停止"的自动跟随。
  * @retval 1=成功，0=失败（控制任务创建失败）
  */
uint8_t Fan_Init(void);

/**
  * @brief  启动风扇（PA1 输出高电平使能）
  * @note   已在运行时重复调用无副作用（幂等）。
  * @retval 无
  */
void Fan_Start(void);

/**
  * @brief  停止/暂停风扇（PA1 输出低电平关闭）
  * @note   已停止时重复调用无副作用（幂等）。
  * @retval 无
  */
void Fan_Stop(void);

/**
  * @brief  切换风扇状态（运行 ↔ 停止）
  * @note   内部为读-改-写，已用临界区保护，避免多任务并发切换时
  *         状态标志错乱；GPIO 电平与状态标志始终成对更新。
  * @retval 无
  */
void Fan_Toggle(void);

/**
  * @brief  查询风扇当前是否运行
  * @retval 1=运行中，0=已停止
  */
uint8_t Fan_IsRunning(void);

#endif /* __APP_FAN_H__ */
