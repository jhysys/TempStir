/**
  ******************************************************************************
  * @file    App_Key.h
  * @brief   按键应用层接口（扫描任务方案）
  * @note    按键位于 Menu 层，负责"按键语义"到"业务动作"的映射：
  *          按键 1（KEY1，PC6，低电平有效）按下 → 聚焦点在
  *          目标温度 → 目标转速 → 目标时间三者间循环切换，
  *          同时蜂鸣器短鸣一声作为操作反馈。
  *          按键 2（KEY2，PC7，低电平有效）→ 修改当前聚焦点的
  *          目标参数：短按（松开前持续 < 1s）数值 +1 并短鸣一声；
  *          长按（按住 ≥ 1s）数值 +10，之后每 300ms 连发 +10，
  *          整个长按过程不鸣叫；长按与短按事件互斥。
  *          按键 3（KEY3，PC8，低电平有效）→ 与按键 2 对称，方向为减：
  *          短按 -1 并短鸣一声；长按 -10 每 300ms 连发，不鸣叫。
  *          按键 4（KEY4，PC9，低电平有效）→ 短按切换系统状态
  *          （空闲 ↔ 运行，启动须满足目标 > 当前的运行条件，条件不
  *          满足长鸣拒绝）；长按 ≥ 1s → 全部数据归零复位（目标温度/
  *          当前温度/目标转速/当前转速/目标时间/当前时间清零），
  *          系统状态强制转空闲，短鸣反馈。
  *          聚焦点的修改通过 Oled_SetFocus()（内部走 SysTem_SetFocus）
  *          完成，保持"按键任务 = 聚焦点唯一写者"的纪律；参数修改
  *          通过 SysTem 对应 setter 完成（自动 3s 延时持久化）；按键的
  *          GPIO 电气属性（输入上拉）由 Core/Src/gpio.c 统一配置，
  *          本模块只读电平，不重复初始化引脚。
  ******************************************************************************
  */
#ifndef __APP_KEY_H__
#define __APP_KEY_H__

#include <stdint.h>

/**
  * @brief  按键模块初始化：创建按键扫描任务
  * @note   必须在 vTaskStartScheduler() 之前调用（创建任务合法），
  *         扫描任务在调度器启动后自动运行；蜂鸣器反馈依赖
  *         Buzzer_Init() 已先行调用（main 中初始化顺序已保证）。
  * @retval 1=成功，0=失败（任务创建失败）
  */
uint8_t Key_Init(void);

#endif /* __APP_KEY_H__ */
